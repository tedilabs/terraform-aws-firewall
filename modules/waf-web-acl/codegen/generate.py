#!/usr/bin/env python3
"""Generate `main.tf` and the statement position tests of the waf-web-acl module.

AWS WAF statements nest up to three levels, and Terraform cannot express recursive
blocks, so each statement block has to be repeated in every position where it may
appear. This script renders those repetitions from one template per statement and
the nesting rules in `statement-grammar.json`.

Usage:
  python3 codegen/generate.py          # rewrite the generated files
  python3 codegen/generate.py --check  # exit 1 if a generated file is out of date

Requires Python 3.9+ and `terraform` on PATH, which formats the output.
"""

import argparse
import json
import pathlib
import re
import subprocess
import sys

MODULE_DIR = pathlib.Path(__file__).resolve().parent.parent
CODEGEN_DIR = MODULE_DIR / "codegen"
GRAMMAR_FILE = MODULE_DIR / "statement-grammar.json"

HEADER = """\
# Code generated by codegen/generate.py. DO NOT EDIT.
# Edit the templates under codegen/ or statement-grammar.json, then run
# `python3 codegen/generate.py` in the module directory.

"""

LOGICAL_STATEMENTS = ("and", "or", "not")

# Minimal input of each leaf statement, used by the generated position tests.
LEAF_FIXTURES = {
    "asn_match": {"asn_list": [64496]},
    "byte_match": {
        "search_string": "/test",
        "positional_constraint": "STARTS_WITH",
        "field_to_match": {"uri_path": {}},
    },
    "geo_match": {"country_codes": ["KR"]},
    "ip_set_reference": {
        "arn": "arn:aws:wafv2:us-east-1:123456789012:regional/ipset/test/12345678-1234-1234-1234-123456789012",
    },
    "label_match": {"scope": "LABEL", "key": "test:label"},
}

# A placeholder alone on its line indents every line of its (multi-line) value to
# match; any other placeholder is replaced inline.
PLACEHOLDER = re.compile(
    r"^(?P<indent>[ \t]*)\{\{(?P<block>\w+)\}\}[ \t]*$|\{\{(?P<inline>\w+)\}\}",
    re.MULTILINE,
)


def fill(template, **values):
    def replace(match):
        if match.group("block"):
            indent = match.group("indent")
            lines = values[match.group("block")].split("\n")
            return "\n".join(indent + line if line else line for line in lines)
        return values[match.group("inline")]

    return PLACEHOLDER.sub(replace, template)


def template(name):
    return (CODEGEN_DIR / name).read_text().rstrip("\n")


def leaf_template(kind, depth):
    # `<kind>.nested.tf.tmpl`, when present, renders the statement below the top level.
    if depth > 1 and (CODEGEN_DIR / "statements" / f"{kind}.nested.tf.tmpl").exists():
        return template(f"statements/{kind}.nested.tf.tmpl")
    return template(f"statements/{kind}.tf.tmpl")


def render_statement(grammar, depth, src):
    """Render every statement allowed at `depth`, each reading its input from `src`."""
    blocks = []
    for kind in grammar[depth - 1]:
        if kind not in LOGICAL_STATEMENTS:
            blocks.append(fill(leaf_template(kind, depth), src=src))
            continue
        if depth == len(grammar):
            raise SystemExit(f"{GRAMMAR_FILE.name}: `{kind}` at level {depth} has no level below it")
        child = f"statement_{depth + 1}"
        blocks.append(fill(
            template(f"logical/{kind}.tf.tmpl"),
            src=src,
            iterator=f"{kind}_{depth}",
            child=child,
            body=render_statement(grammar, depth + 1, f"{child}.value"),
        ))
    return "\n\n".join(blocks)


def render_main(grammar):
    return HEADER + fill(
        template("main.tf.tmpl"),
        rule_statement=render_statement(grammar["rule"], 1, "rule.value.statement"),
    )


def positions(grammar, path=()):
    """Yield the logical operators leading to each statement level, with its leaf statements."""
    kinds = grammar[len(path)]
    yield path, [kind for kind in kinds if kind not in LOGICAL_STATEMENTS]
    for kind in kinds:
        if kind in LOGICAL_STATEMENTS:
            yield from positions(grammar, path + (kind,))


def wrap(statement, path):
    for op in reversed(path):
        if op == "not":
            statement = {"not": {"statement": statement}}
        else:
            statement = {op: {"statements": [statement, statement]}}
    return statement


def rendered(rule_name, path):
    """An expression listing the planned statement blocks reached through `path`."""
    expr = f'[for rule in aws_wafv2_web_acl.this.rule : rule.statement[0] if rule.name == "{rule_name}"]'
    for op in path:
        if op == "not":
            expr = f"[for s in {expr} : s.not_statement[0].statement[0]]"
        else:
            expr = f"flatten([for s in {expr} : s.{op}_statement[0].statement])"
    return expr


def hcl(value, indent=0):
    pad = "  " * indent
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = "".join(f"{pad}  {key} = {hcl(item, indent + 1)}\n" for key, item in value.items())
        return "{\n" + items + pad + "}"
    if isinstance(value, list):
        if all(not isinstance(item, (dict, list)) for item in value):
            return "[" + ", ".join(hcl(item) for item in value) + "]"
        items = "".join(f"{pad}  {hcl(item, indent + 1)},\n" for item in value)
        return "[\n" + items + pad + "]"
    return json.dumps(value)


def render_tests(grammar):
    runs = []
    for path, kinds in positions(grammar["rule"]):
        position = "_".join(path) or "root"
        rules = [
            {
                "name": kind,
                "priority": priority,
                "action": "BLOCK",
                "statement": wrap({kind: LEAF_FIXTURES[kind]}, path),
            }
            for priority, kind in enumerate(kinds)
        ]
        count = 2 ** sum(op != "not" for op in path)
        asserts = "\n\n".join(
            f"  assert {{\n"
            f"    condition = alltrue([\n"
            f"      length({rendered(kind, path)}) == {count},\n"
            f"      alltrue([for s in {rendered(kind, path)} : length(s.{kind}_statement) == 1]),\n"
            f"    ])\n"
            f'    error_message = "`{kind}` must render in the {position} position."\n'
            f"  }}"
            for kind in kinds
        )
        runs.append(
            f'run "{position}" {{\n'
            f"  command = plan\n\n"
            f"  variables {{\n"
            f"    rules = {hcl(rules, 2)}\n"
            f"  }}\n\n"
            f"{asserts}\n"
            f"}}\n"
        )
    return HEADER + template("tests.tftest.hcl.tmpl") + "\n\n" + "\n".join(runs)


OUTPUTS = {
    "main.tf": render_main,
    "tests/statement_positions.tftest.hcl": render_tests,
}


def terraform_fmt(text):
    result = subprocess.run(["terraform", "fmt", "-"], input=text, capture_output=True, text=True)
    if result.returncode != 0:
        raise SystemExit(f"terraform fmt failed:\n{result.stderr}")
    return result.stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if a generated file is out of date")
    args = parser.parse_args()

    grammar = json.loads(GRAMMAR_FILE.read_text())
    stale = []
    for name, render in OUTPUTS.items():
        path = MODULE_DIR / name
        content = terraform_fmt(render(grammar))
        if path.exists() and path.read_text() == content:
            continue
        if args.check:
            stale.append(name)
        else:
            path.write_text(content)
            print(f"generated {name}")

    if stale:
        print(f"out of date: {', '.join(stale)}; run `python3 codegen/generate.py`", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
